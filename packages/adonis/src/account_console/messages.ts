/** The labels the card mounters show, in the console locale (they run in the browser). */
export function cardLabels(locale: string): Record<string, string> {
  const catalog =
    ACCOUNT_MESSAGES[locale] ??
    ACCOUNT_MESSAGES[locale.split('-')[0] === 'pt' ? 'pt-BR' : 'en'] ??
    ACCOUNT_MESSAGES.en!;
  const label = (key: string) =>
    catalog[`payments.card.${key}`] ?? ACCOUNT_MESSAGES.en![`payments.card.${key}`] ?? key;
  return {
    number: label('number'),
    holder: label('holder'),
    expiry: label('expiry'),
    cvc: label('cvc'),
    document: label('document'),
    postalCode: label('postal_code'),
    addressNumber: label('address_number'),
    phone: label('phone'),
    save: label('save'),
    saving: label('saving'),
    failed: label('failed'),
  };
}
